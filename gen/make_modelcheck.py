#!/usr/bin/env python3
"""Writes ModelCheck.lean: the Lean model (A393317/Defs.lean) against published OEIS data.

Usage:  python3 gen/make_modelcheck.py <path to a checkout of github.com/oeis/oeisdata> > ModelCheck.lean

For each of the ten OEIS entries "Halting time for Wolfram's 2-state 2-symbol Turing machine M when
started with n on the tape" all terms stored in the entry (the %S, %T and %U lines) are taken over.
"""
import sys, re, os
SEQS = [("A393103", 1285), ("A393106", 261), ("A393146", 3333), ("A393190", 3111), ("A393209", 1511),
        ("A393210", 3626), ("A393212", 773), ("A393232", 897), ("A393233", 919), ("A393234", 3239)]
root = sys.argv[1]
out = []
out.append('''import A393317.Defs

/-!
# The model against OEIS data

The definitions in `A393317/Defs.lean` were written for this project.  This file tests them against
data computed by others: for ten machines the OEIS contains the sequence of halting times on the
inputs `n = 1, 2, 3, …` (entries by Sean A. Irvine, Feb 2026).  For every term stored in these
entries we prove, inside the Lean kernel, that the machine of the model halts after exactly that
many steps.  (File generated by `gen/make_modelcheck.py` from the OEIS data.)
-/

namespace A393317

/-- Simulator with a step budget, built from `step`: the halting time if the machine halts within
`fuel` steps. -/
def haltTime (m : ℕ) : ℕ → Config → Option ℕ
  | 0, _ => none
  | fuel + 1, c =>
    match step m c with
    | none => some 1
    | some c' => (haltTime m fuel c').map (· + 1)

theorem haltTime_sound {m : ℕ} : ∀ {fuel : ℕ} {c : Config} {t : ℕ},
    haltTime m fuel c = some t → HaltsAfter m c t
  | 0, _, _, h => by simp [haltTime] at h
  | fuel + 1, c, t, h => by
    unfold haltTime at h
    split at h
    · next hs =>
      cases h
      exact HaltsAfter.halt hs
    · next c' hs =>
      cases h' : haltTime m fuel c' with
      | none => simp [h'] at h
      | some t' =>
        simp only [h', Option.map_some, Option.some.injEq] at h
        subst h
        exact HaltsAfter.next hs (haltTime_sound h')

/-- Machine `m` halts on the inputs `off, off + 1, …` after exactly the listed numbers of steps. -/
def agrees (m : ℕ) : ℕ → List ℕ → Bool
  | _, [] => true
  | off, t :: ts => (haltTime m t (init off) == some t) && agrees m (off + 1) ts

theorem agrees_sound {m : ℕ} : ∀ {off : ℕ} {ts : List ℕ}, agrees m off ts = true →
    ∀ (i : ℕ) (h : i < ts.length), HaltsAfter m (init (off + i)) ts[i]
  | _, [], _, i, h => by simp at h
  | off, t :: ts, ha, i, h => by
    simp only [agrees, Bool.and_eq_true, beq_iff_eq] at ha
    cases i with
    | zero => exact haltTime_sound ha.1
    | succ i =>
      have := agrees_sound ha.2 i (by simpa using h)
      simpa [Nat.add_assoc, Nat.add_comm 1 i] using this
''')
total = 0
for a, m in SEQS:
    f = os.path.join(root, 'seq', a[:4], a + '.seq')
    terms = []; off = None; name = None
    for l in open(f, encoding='utf-8'):
        if l[:2] in ('%S', '%T', '%U'): terms += [int(x) for x in l[11:].strip().strip(',').split(',')]
        if l[:2] == '%O': off = int(l[11:].split(',')[0])
        if l[:2] == '%N': name = l[11:].strip()
    assert off == 1 and str(m) in name and 'Halting time' in name, (a, off, name)
    total += len(terms)
    rows = []; row = '  ['
    for i, t in enumerate(terms):
        s = str(t) + (', ' if i + 1 < len(terms) else ']')
        if len(row) + len(s) > 98: rows.append(row.rstrip()); row = '   '
        row += s
    rows.append(row)
    out.append('/-- OEIS %s: %s  (%d terms, `n = 1, …, %d`). -/' % (a, name, len(terms), len(terms)))
    out.append('def oeis_%s : List ℕ :=\n%s\n' % (a, '\n'.join(rows)))
    out.append('/-- The model reproduces every stored term of OEIS %s (machine %d). -/' % (a, m))
    out.append('theorem model_%s : ∀ (i : ℕ) (h : i < oeis_%s.length),\n    HaltsAfter %d (init (1 + i)) oeis_%s[i] :=\n  agrees_sound (by decide +kernel)\n' % (a, a, m, a))
out.append('end A393317')
print('\n'.join(out))
sys.stderr.write('%d terms\n' % total)
