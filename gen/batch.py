#!/usr/bin/env python3
"""Produces all certificates and writes them as Lean files  <outdir>/C<k>.lean  (64 machines each)
together with  <outdir>/../All.lean.

Usage (from the directory gen/):   python3 batch.py ../A393317/Certs

The parameters (J, j, c) that are known to work are read from params.txt; if they fail (or for a
machine that is not listed) a short list of other parameters is tried.  The four machines 1507,
2574, 2830, 3555 have no certificate; they are treated by hand in A393317/Special.lean.
Needs numpy and scipy (linear programming).
"""
import sys, os, multiprocessing as mp, signal
from gencert import make, lean_cert, Fail
SPECIAL={1507,2574,2830,3555}
PARAMS1=[(0,0),(1,0),(1,1),(2,0),(2,1),(3,0),(2,2)]
def job(num):
    if num in SPECIAL: return (num,None,'special')
    first=KNOWN.get(num)
    tries=[]
    if first: tries.append(first)
    for J,j in PARAMS1:
        if (J,j,1) not in tries: tries.append((J,j,1))
    for J,j in [(0,0),(1,0),(1,1),(2,0)]:
        if (J,j,2) not in tries: tries.append((J,j,2))
    errs=[]
    for (J,j,c) in tries:
        try:
            signal.alarm(120)
            C=make(num,J,j,c)
            signal.alarm(0)
            size=sum(len(C[k]) for k in ('fI','fB','gI','gB','tI','tB','tD','uI','uB','uD'))
            return (num,(J,j,c,C['N'],size,C['D']),lean_cert(C))
        except Fail as e: errs.append('%s:%s'%((J,j,c),e))
        except Exception as e: errs.append('%s:EXC %r'%((J,j,c),e))
        finally: signal.alarm(0)
    return (num,None,'FAIL '+'; '.join(errs))
def _alarm(sig,frm): raise Fail('time limit')
KNOWN={}
for l in open(os.path.join(os.path.dirname(os.path.abspath(__file__)),'params.txt')):
    if l.startswith('#') or not l.strip(): continue
    p=[int(x) for x in l.split()]
    KNOWN[p[0]]=(p[1],p[2],p[3])
if __name__=='__main__':
    signal.signal(signal.SIGALRM,_alarm)
    outdir=sys.argv[1]
    os.makedirs(outdir,exist_ok=True)
    with mp.Pool(os.cpu_count() or 4) as pool: res=pool.map(job,range(4096),chunksize=4)
    info=open(os.path.join(outdir,'..','..','gen','certs_info.txt') if len(sys.argv)<3 else sys.argv[2],'w'); fails=[]
    for k in range(64):
        lines=['import A393317.UB','','/-! Certificates for machines %d–%d (generated by `gen/batch.py`). -/'%(64*k,64*k+63),'','namespace A393317','namespace Certs','']
        cases=[]
        for num,meta,txt in res[64*k:64*k+64]:
            if meta is None:
                info.write('%d %s\n'%(num,txt[:300]))
                if txt!='special': fails.append(num); cases.append('  · sorry')
                else: cases.append('  · exact ub%d'%num)
                continue
            J,j,c,N,size,D=meta
            info.write('%d ok J=%d j=%d c=%d N=%d size=%d D=%d\n'%(num,J,j,c,N,size,D))
            ty='Cert' if c==1 else 'CertE'
            lines.append('def c%d : %s :=\n  %s\n'%(num,ty,txt))
            lines.append('theorem ok%d : c%d.check %d = true := by decide +kernel\n'%(num,num,num))
            cases.append('  · exact UB.of_cert%s ok%d'%('' if c==1 else 'E',num))
        lines.append('theorem chunk%d : ∀ m : ℕ, %d ≤ m → m < %d → UB m := by\n  intro m h1 h2\n  interval_cases m\n%s\n'%(k,64*k,64*k+64,'\n'.join(cases)))
        lines+=['end Certs','end A393317','']
        open(os.path.join(outdir,'C%d.lean'%k),'w').write('\n'.join(lines))
    main=['\n'.join('import A393317.Certs.C%d'%k for k in range(64)),'','/-! All 4096 machines (generated by `gen/batch.py`). -/','','namespace A393317','',
          '/-- **Every machine satisfies the upper bound.** -/','theorem ub_all : ∀ m : ℕ, m < 4096 → UB m := by','  intro m hm',
          '  obtain ⟨k, hk⟩ : ∃ k, k = m / 64 := ⟨_, rfl⟩','  have hk64 : k < 64 := by omega','  interval_cases k']
    for k in range(64): main.append('  · exact Certs.chunk%d m (by omega) (by omega)'%k)
    main+=['','end A393317','']
    open(os.path.join(outdir,'..','All.lean'),'w').write('\n'.join(main))
    print('failures:',fails)
